export function projectsInGroup(groupId: ProjectIndexGroupId): Project[] {
  const group = projectIndexGroups.find((item) => item.id === groupId);
  if (!group) {
    return [];
  }

  return projects.filter((project) => group.kinds.includes(project.kind));
}

