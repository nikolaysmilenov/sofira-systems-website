const aboutProjectSlugs = ["sofira-systems", "hr-hub-360", "stinger"] as const;

export const aboutSystems = {
  coord: "REAL SYSTEMS",
  title: "Системи, които изграждаме.",
  description:
    "Публикуваме собствени системи с ясен статус. Без измислени клиенти, метрики или резултати.",
  items: aboutProjectSlugs.map((slug) => {
    const project = projects.find((item) => item.slug === slug);
    if (!project) {
      throw new Error(`Missing about-page project: ${slug}`);
    }

    const kind = projectKindLabel[project.kind];
    const status = projectStatusLabel[project.status];

    return {
      index: project.index,
      name: project.name,
      href: projectPath(slug),
      kicker:
        project.kind === "public-platform" ? kind : `${kind} / ${status}`,
      summary: project.summary,
    };
  }),
};

