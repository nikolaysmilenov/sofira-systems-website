export function resourcePath(slug: string): string {
  return `${routes.resources}/${slug}`;
}

export function getResourceBySlug(slug: string): ResourceArticle | undefined {
  return resources.find((article) => article.slug === slug);
}

export function formatResourceDate(date: string): string {
  return new Intl.DateTimeFormat("bg-BG", {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(`${date}T12:00:00Z`));
}
